"""Build D3/base.js, the state outlines every display layer is drawn against and clipped to.

Added 2026-09-14 (Nathan: natural features "as sharp as possible"). base.js had been made by hand on
2026-09-08 from Census cb_2023_us_state_20m (1:20,000,000, generalised by about a kilometre, 1,964
vertices for nine states). This rebuilds it from the SAME PRODUCT AND VINTAGE at 1:500,000,
cb_2023_us_state_500k, so the coastline, the state borders, and everything clipped to them (relief,
lakes, rivers, fish data) are sharp when zoomed in.

Cartographic boundary files (cb_*) are clipped to the shoreline. The TIGER/Line state files in
WORKING/CENSUS/ used by the joins are NOT: they extend into coastal water, which would be wrong as a
coastline. The joins are not affected by this file.

Readers of base.js, all to be re-run after this: make_habitat_display.py (off-map test),
make_presence_display.py (off-map test), make_natural_features.py (relief mask, labels),
make_relief_hi.py (tile set, mask).

Run: python3 build/make_base_outlines.py
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
CENSUS = ROOT / "WORKING/CENSUS"
ZIP = CENSUS / "cb_2023_us_state_500k.zip"
URL = "https://www2.census.gov/geo/tiger/GENZ2023/shp/cb_2023_us_state_500k.zip"
OUT = ROOT / "D3/base.js"
STATES = ("CA", "OR", "WA", "ID", "MT", "NV", "UT", "WY", "AZ")   # the nine base.js has always drawn
PRECISION = 5   # about 1 m; finer than the 1:500k source can resolve, so no detail is lost to rounding


def main():
    if not ZIP.exists():
        subprocess.run(["curl", "-sf", "--retry", "3", "-o", str(ZIP), URL], check=True)
    where = "STUSPS IN (" + ",".join(f"'{s}'" for s in STATES) + ")"
    r = subprocess.run(["ogr2ogr", "-f", "GeoJSON", "/vsistdout/", f"/vsizip/{ZIP}/cb_2023_us_state_500k.shp",
                        "-where", where, "-select", "STUSPS,NAME", "-t_srs", "EPSG:4326",
                        "-lco", f"COORDINATE_PRECISION={PRECISION}", "-lco", "RFC7946=NO", "-nln", "cb_2023_us_state_500k"],
                       check=True, capture_output=True, text=True)
    gj = json.loads(r.stdout)
    got = sorted(f["properties"]["STUSPS"] for f in gj["features"])
    assert got == sorted(STATES), got
    verts = sum(len(ring) for f in gj["features"]
                for poly in ([f["geometry"]["coordinates"]] if f["geometry"]["type"] == "Polygon" else f["geometry"]["coordinates"])
                for ring in poly)
    OUT.write_text("// generated by build/make_base_outlines.py: western state outlines, US Census cb_2023_us_state_500k "
                   f"(public domain)\nconst STATES = {json.dumps(gj, separators=(',', ':'))};\n")
    print(f"{OUT.name}: {len(got)} states, {verts:,} vertices, {OUT.stat().st_size / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
