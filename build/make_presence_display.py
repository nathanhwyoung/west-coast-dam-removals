SQ = lambda v: v.replace("'", "''")          # single quotes in a source name would break the SQL
RUN = "coalesce(nullif(run,''),'-')"        # a blank run and a NULL run are the same thing: no run


def export(species, layer):
    """Every feature of one species from one layer, CARRYING its source and run.

    One call per species per layer, split in Python afterwards. Querying each source separately would
    be ~90 scans of a 140,815-line layer for the same result.
    """
    r = subprocess.run(["ogr2ogr", "-f", "GeoJSON", "/vsistdout/", str(GPKG),
                        "-dialect", "sqlite",
                        "-sql", f"SELECT geom, state, source_data, {RUN} AS run, claim_grade, grain "
                                f"FROM {layer} WHERE species = '{SQ(species)}'",
                        "-simplify", "0.0003", "-lco", "COORDINATE_PRECISION=4", "-dim", "XY"],
                       check=True, capture_output=True, text=True)
    return json.loads(r.stdout)["features"]


def export_range_merged(species, pairs):
    """One SWITCH's watershed ranges, dissolved into their outer boundary.

    Added 2026-09-16 ALONGSIDE the per-watershed rings, not instead of them: which geometry the map
    should use is Nathan's call and the page carries both.

    Why it exists: undissolved, the ranges draw as a web of thin coloured lines that reads as streams
    (SPECIES_LAYERS.md, "Which map lines are not waterways"), and 98% of those segments are internal
    edges, either the boundary two neighbouring watersheds share or the same watershed repeated for
    another run of the same species.

    It also makes an even-odd FILL correct. Rings are stored flattened, so two copies of one watershed
    cancel each other under even-odd and would fill as a hole; after the union each area appears once
    and only real holes cancel.

    DISSOLVED PER SWITCH, not per species: a union across switches would leave a shape that still
    contained one the reader had turned off. It takes a LIST of (source, run) pairs because a switch can
    span several source rows (PISCES Central Valley is three runs, three source_data values).
    Grouping runs into one switch gives some of the dissolve back, since runs of one population overlap.

    DISPLAY ONLY. The join reads the full-resolution ranges one at a time and is untouched.
    """
    where = " OR ".join(f"(source_data = '{SQ(src)}' AND {RUN} = '{SQ(run)}')" for src, run in pairs)
    r = subprocess.run(["ogr2ogr", "-f", "GeoJSON", "/vsistdout/", str(GPKG),
                        "-dialect", "sqlite",
                        "-sql", f"SELECT ST_Union(geom) AS geom FROM presence_ranges "
                                f"WHERE species = '{SQ(species)}' AND ({where})",
                        "-simplify", "0.0003", "-lco", "COORDINATE_PRECISION=4", "-dim", "XY"],
                       check=True, capture_output=True, text=True)
    return json.loads(r.stdout)["features"]


def rings_of(features):
    """Polygon features flattened TO RINGS, the format of the ESA display files, which both pages'
    drawing code expects. Until 2026-09-14 (as first written in make_maplibre_test.py) each entry was
    a whole polygon, one level too deep: neither page threw, and neither drew a single range polygon."""
    rings = []
    for f in features:
        g = f["geometry"]
        if g:
            for poly in ([g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]):
                rings += poly
    assert all(isinstance(r[0][0], (int, float)) for r in rings), "polys must be a list of rings"
    return rings


# A checkbox needs a short name, and the source strings are long and inconsistent in where they put
# the run: ODFW spells it into the layer name (fhd_ChinookFall), SWIFD keeps ONE source string for the
# whole geodatabase and varies the run column, PISCES uses a species-code suffix. So the KEY IS THE PAIR
# (source, run), which is the only grain that is consistent across all of them: keying on the source
# alone would give ODFW a switch per run while lumping every Washington run into one.
PROGRAMME = [
    ("ODFW Fish Habitat Distribution", "ODFW"),
    ("WDFW SWIFD", "SWIFD"),
    ("NOAA ds981", "NOAA ds981"),
    ("NOAA ds982", "NOAA ds982"),
    ("CDFW BIOS ds326", "CDFW ds326"),
    ("CDFW BIOS ds340", "CDFW ds340"),
    ("CDFW BIOS ds341", "CDFW ds341"),
    ("USFWS Pacific Lamprey Known Observations", "USFWS 2022"),
    ("USFWS ds2673", "USFWS ds2673"),
    ("PISCES", "PISCES"),
]


# PISCES names a run as "<population> <run type>". Stripping the run type groups the runs of one
# population into a single switch, which is what Nathan asked for: Chinook's six PISCES runs become
# Upper Klamath-Trinity, SONCC and Central Valley. A run with NO run type (green sturgeon's Northern
# and Southern DPS, redband's McCloud River and Goose Lake) keeps its own switch, which is right:
# those are distinct populations, not runs of one.
#
# NOTE ON "SONCC": PISCES SOT03 is the Southern Oregon/Northern California Coast CHINOOK range, a
# published PISCES layer. It is NOT this project's derived SONCC coho reconstruction, which lives in
# the ESA tier. It must not be labelled "derived": that would claim our own work where there is none.
RUN_TYPES = ["late fall", "fall", "spring", "summer", "winter"]


def pisces_population(run):
    low = run.lower()
    for t in RUN_TYPES:
        if low.endswith(" " + t):
            return run[: -len(t) - 1].strip()
    return run


def programme_of(source):
    return next((short for prefix, short in PROGRAMME if source.startswith(prefix)), source)


# What a source's geometry MEANS, where it is not simply "a reach where the fish was recorded"
# (Nathan, 2026-09-16: an "i" beside the obvious cases). The trigger is principled rather than a list
# I picked: any claim grade other than `observed`, plus the one source whose LINES are derived.
# Counts are filled in by the caller so the note says how much of the switch it applies to.
NOTES = {
    "range": "Not a stream. PISCES maps fish onto whole HUC12 watersheds, a median of about 3 km "
             "across, so the shape says the fish is somewhere in this watershed, not that it is in "
             "any particular channel. Every California species is mapped this way; Oregon and "
             "Washington are mapped onto stream arcs instead. The change of shape at the state line "
             "is a change of institution, not of fish.",
    "presumed": "{n} of these reaches are presumed rather than recorded: the source marks them as "
                "likely habitat, not as a documented observation.",
    "inferred": "These {n} reaches are this project's inference, not a label in the source. SWIFD has "
                "no redband category, so redband is read as Rainbow Trout east of the Cascades with a "
                "fluvial or adfluvial life history. Redband is understated wherever the source "
                "recorded no life history at all.",
}
# Keyed on the programme short name, for meanings that are not about the claim grade.
SOURCE_NOTES = {
    "USFWS ds2673": "These lines are derived by USFWS from NHDPlusV2, fourth-order streams and above, "
                    "rather than traced from observations. The derivation is the agency's, not this "
                    "project's.",
}


def notes_for(programme, grade_counts):
    out = []
    for grade, n in sorted(grade_counts.items()):
        if grade in NOTES:
            out.append(NOTES[grade].format(n=f"{n:,}"))
    if programme in SOURCE_NOTES:
        out.append(SOURCE_NOTES[programme])
    return out


def group_of(state, source, run):
    """The switch one (state, source, run) belongs to, as (id, label, sort key).

    Regrouped 2026-09-16 at Nathan's request: 68 switches was too many. Runs inside one programme merge
    into one switch (ODFW's Chinook fall and spring become "ODFW, Fall + Spring"), and PISCES groups by
    population. Ordered so REACH sources come before RANGE sources, so the list reads by geometry: the
    streams first, then the watersheds.
    """
    prog = programme_of(source)
    # Grouped BY STATE since 2026-09-16 (Nathan), which splits nothing: measured, no source spans more
    # than one state. `US` is the two federal USFWS lamprey layers, which the state line does not limit
    # (standing rule 39), so it sorts last rather than pretending to be a state.
    order = (["CA", "OR", "WA", "US"].index(state) if state in ("CA", "OR", "WA", "US") else 9,
             1 if prog == "PISCES" else 0)
    if prog == "PISCES":
        pop = pisces_population(run) if run and run != "-" else ""
        name = f"PISCES, {pop}" if pop else "PISCES"
        return (f"{state}_pisces_{pop}".strip("_"), f"{state}, {name}", order)
    return (f"{state}_{prog}", f"{state}, {prog}", order)


def slug(gid):
    """A stable id for one switch. NOT Python's hash(): that is randomised per process, so the ids, and
    therefore the generated files, would differ between runs of the same build."""
    stem = "".join(c.lower() if c.isalnum() else "_" for c in gid).strip("_")[:60]
    return f"{stem}_{zlib.crc32(gid.encode()) % 997:03d}"


def build_species(key, species, states):
    """One file per species, holding ONE ENTRY PER SWITCH since 2026-09-16 (Nathan asked for a switch
    per source, then for the runs inside a programme to be grouped). Geometry is NOT also stored
    combined: at 38 MB for the 21 species that would double the folder. Both pages rebuild the combined
    view at load time through presenceCombined() in index.js, which is written by this script so the two
    pages cannot drift (standing rule 44)."""
    groups = {}
    for layer, kind in (("presence_lines", "lines"), ("presence_ranges", "polys")):
        for f in export(species, layer):
            g, pr = f["geometry"], f["properties"]
            if not g:
                continue
            gid, label, order = group_of(pr["state"], pr["source_data"], pr["run"])
            d = groups.setdefault(gid, {"label": label, "order": order, "state": pr["state"],
                                        "programme": programme_of(pr["source_data"]),
                                        "lines": [], "polys": [], "pairs": set(), "runs": [],
                                        "grades": {}, "grains": set()})
            d["pairs"].add((pr["source_data"], pr["run"]))
            if pr["run"] and pr["run"] != "-" and pr["run"] not in d["runs"]:
                d["runs"].append(pr["run"])
            d["grades"][pr["claim_grade"]] = d["grades"].get(pr["claim_grade"], 0) + 1
            d["grains"].add(pr["grain"])
            if kind == "lines":
                d["lines"] += [g["coordinates"]] if g["type"] == "LineString" else g["coordinates"]
            else:
                d["polys"] += rings_of([f])

    sources, degenerate, offmap = [], 0, 0
    for gid, d in sorted(groups.items(), key=lambda kv: (kv[1]["order"], kv[1]["label"])):
        lines, polys = d["lines"], d["polys"]
        merged = rings_of(export_range_merged(species, sorted(d["pairs"]))) if polys else []
        # Parts under 2 points draw nothing (ogr2ogr's simplify leaves empty parts inside some multi-lines).
        before = len(lines) + len(polys)
        lines = [l for l in lines if len(l) >= 2]
        polys = [r for r in polys if len(r) >= 2]
        degenerate += before - len(lines) - len(polys)
        before = len(lines) + len(polys)
        lines = [l for l in lines if not off_map(l, *states)]
        polys = [r for r in polys if not off_map(r, *states)]
        offmap += before - len(lines) - len(polys)
        merged = [r for r in merged if len(r) >= 2 and not off_map(r, *states)]
        # A union cannot lose area, so an EMPTY merged set beside real ranges is the dissolve failing.
        assert bool(merged) == bool(polys), f"merged ranges disagree for {species!r} / {gid!r}"
        if not (lines or polys):
            continue                       # everything this switch had lay off the map
        # PISCES already names its population in the label, so only a programme's runs are appended:
        # "ODFW, Fall + Spring". Merged runs are what makes 68 switches into something readable.
        label = d["label"]
        if d["programme"] != "PISCES" and d["runs"]:
            label += ", " + " + ".join(d["runs"])
        sources.append({"id": slug(gid), "label": label, "runs": d["runs"],
                        "sources": sorted({src for src, _ in d["pairs"]}),
                        "state": d["state"], "grade": "/".join(sorted(d["grades"])),
                        "grades": d["grades"], "grain": "/".join(sorted(d["grains"])),
                        "notes": notes_for(d["programme"], d["grades"]),
                        "lines": lines, "polys": polys, "polys_merged": merged})

    # A misspelt species name returns no rows, which would read as a real absence (PISCES spelling traps).
    assert sources, f"no geometry for {species!r}"
    # POLYS IS NOT WRITTEN TO THE FILE, 2026-09-18. The per-watershed rings have not been read by the
    # page since the geometry question was settled as merged on 09-17: both the screen path and the pick
    # canvas use polys_merged. It was 5.56 MB of 40.16, and the page paid a projection pass per repack
    # to place geometry it never painted.
    # IT IS STILL COMPUTED, AND STILL LIVES IN `sources` IN MEMORY, DELIBERATELY. Two things need it:
    #   1. the guard and the assert above (a union cannot lose area, so an empty merged set beside real
    #      polys is the dissolve failing, and that is the only alarm on it);
    #   2. main() below, which puts its COUNT in index.js. That count is what each source switch shows,
    #      and it is the meaningful number: Chinook covers 766 watersheds, while 42 is a fact about the
    #      file rather than about the fish.
    # So it is stripped here, at the point of serialisation, and nowhere else.
    slim = [{k: v for k, v in s.items() if k != "polys"} for s in sources]
    body = json.dumps({"label": species, "sources": slim}, separators=(",", ":"))
    p = OUT / f"presence_{key}.js"
    p.write_text(f"{HEADER}PRESENCE[{json.dumps(key)}]={body};\n")
    return sources, p, degenerate, offmap


# Written into index.js so the page gets ONE definition of how per-source geometry recombines into the
# whole-species view, rather than the page carrying its own copy. Standing rule 44: a rule in two files
# has two chances to be wrong and no way to notice. There were two pages until 2026-09-17, when
# species_test.html replaced index.html and the old species display went to _OLD/D3/.
COMBINE = """
// Combine a species' per-source geometry into one whole-species view. `only` is a Set of source ids to
// include, or null for all of them. Written by build/make_presence_display.py rather than kept in the
// page, so the rule has one definition (standing rule 44).
function presenceCombined(raw, only) {
  // polys dropped 2026-09-18: the per-watershed rings are no longer written to the data files, so
  // concatenating s.polys here would throw on undefined. Ranges are merged geometry only.
  const out = { lines: [], polys_merged: [] };
  if (!raw || !raw.sources) return out;
  for (const s of raw.sources) {
    if (only && !only.has(s.id)) continue;
    out.lines = out.lines.concat(s.lines);
    out.polys_merged = out.polys_merged.concat(s.polys_merged);
  }
  return out;
}
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    index = []
    states = load_states()
    for key, (species, colour) in PRESENCE.items():
        sources, p, degenerate, offmap = build_species(key, species, states)
        nl = sum(len(s["lines"]) for s in sources)
        nr = sum(len(s["polys"]) for s in sources)
        rverts = sum(len(r) for s in sources for r in s["polys"])
        verts = sum(len(l) for s in sources for l in s["lines"]) + rverts
        mverts = sum(len(r) for s in sources for r in s["polys_merged"])
        nm = sum(len(s["polys_merged"]) for s in sources)
        mb = p.stat().st_size / 1e6
        index.append({"key": key, "label": species, "colour": colour, "lines": nl, "polys": nr,
                      "polys_merged": nm, "vertices": verts, "vertices_ranges": rverts,
                      "vertices_merged": mverts, "mb": round(mb, 2),
                      "parts_dropped_as_degenerate": degenerate, "parts_dropped_off_map": offmap,
                      "sources": [{"id": s["id"], "label": s["label"], "sources": s["sources"],
                                   "runs": s["runs"], "state": s["state"], "notes": s["notes"], "grade": s["grade"], "grain": s["grain"],
                                   "lines": len(s["lines"]), "polys": len(s["polys"]),
                                   "polys_merged": len(s["polys_merged"])} for s in sources]})
        extra = f", ranges {nr}/{rverts} merge to {nm}/{mverts}" if nr else ""
        print(f"{p.name}: {len(sources)} sources, {nl} lines, {nr} polygons, {verts} vertices, "
              f"{mb:.1f} MB, dropped {degenerate} degenerate + {offmap} off-map parts{extra}")
    (OUT / "index.js").write_text(
        f"{HEADER}const PRESENCE_INDEX = {json.dumps(index, indent=1)};\n{COMBINE}")
    rng = [i for i in index if i["polys"]]
    print(f"{len(index)} species, {sum(len(i['sources']) for i in index)} sources, "
          f"{sum(i['vertices'] for i in index)} vertices, "
          f"{sum(i['parts_dropped_as_degenerate'] for i in index)} degenerate + "
          f"{sum(i['parts_dropped_off_map'] for i in index)} off-map parts dropped")
    print(f"{len(rng)} species carry watershed ranges: "
          f"{sum(i['polys'] for i in rng)} rings / {sum(i['vertices_ranges'] for i in rng)} vertices per watershed, "
          f"{sum(i['polys_merged'] for i in rng)} / {sum(i['vertices_merged'] for i in rng)} merged")


if __name__ == "__main__":
    main()
