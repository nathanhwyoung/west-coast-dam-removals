"""Build the species-presence display files for D3/index.html.

Added 2026-09-14 as a renderer load test; now the map's real presence layer. Renamed from
make_presence_test.py, with D3/presence_test/ -> D3/presence/, on 2026-09-15. Writes D3/presence/:

  presence_{key}.js   one file per species, simplified exactly like the ESA display copies
      (0.0003 degrees, 4 dp), as PRESENCE[key] = {label, lines, polys} in lon/lat. Loaded by
      script injection so the D3 page still opens from file://.
  index.js            PRESENCE_INDEX: key, label, test colour, line/polygon/vertex counts, size.

Read by D3/index.html (all 21). Split out of build/make_maplibre_test.py the same day; the
MapLibre test was deleted once D3 was chosen (2026-09-14). Display only; nothing here is read by the join or the audits.
Parts lying wholly in a non-project state (and not within 3 km of CA, OR or WA) are dropped, using
make_habitat_display.py's own off_map() and outline loader, imported not copied (standing rule 44),
added 2026-09-14 when Nathan chose to show the six neighbouring states as flat outlines only. Parts
that cross a border stay whole here; D3/index.html clips them visually at the drawn border.

Run: python3 build/make_presence_display.py   (about a minute)
"""

